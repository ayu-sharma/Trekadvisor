/** One-way road access from a starting point, with a sane fallback. */
export function accessFrom(destination, origin) {
  const a = destination.access;
  if (origin && a[origin]) return a[origin];
  // "Somewhere else" — assume the traveller reaches the plains first, and
  // score them on the average of the two main gateways.
  const km = Math.round((a.delhi.km + a.chandigarh.km) / 2);
  const hrs = Math.round(((a.delhi.hrs + a.chandigarh.hrs) / 2) * 2) / 2;
  return { km, hrs, assumed: true };
}
